-- Фильмы
CREATE TABLE IF NOT EXISTS films
(
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar,
    description varchar,
    releaseDate timestamp,
    duration    integer NOT NULL,
    rating_id   integer NOT NULL
);

-- Пользователи
CREATE TABLE IF NOT EXISTS users
(
    id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email    varchar UNIQUE,
    login    varchar NOT NULL UNIQUE,
    name     varchar NOT NULL,
    birthday date    NOT NULL
);

-- Друзья
CREATE TABLE IF NOT EXISTS friends
(
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id   integer NOT NULL,
    friend_id integer NOT NULL,
    status    varchar NOT NULL
);

-- Лайки фильмам
CREATE TABLE IF NOT EXISTS likes
(
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    film_id integer NOT NULL,
    user_id integer NOT NULL
);

-- Жанры фильмов
CREATE TABLE IF NOT EXISTS film_genre
(
    id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    film_id  integer NOT NULL,
    genre_id integer NOT NULL
);

-- Режиссеры фильмов
CREATE TABLE IF NOT EXISTS film_director
(
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    film_id     integer NOT NULL,
    director_id integer NOT NULL
);

-- Жанры
CREATE TABLE IF NOT EXISTS genres
(
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar UNIQUE NOT NULL
);

-- Режиссеры
CREATE TABLE IF NOT EXISTS directors
(
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar UNIQUE NOT NULL
);

-- Рейтинг
CREATE TABLE IF NOT EXISTS mpa
(
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar unique NOT NULL
);

-- Представление для быстрого доступа к статистике
CREATE VIEW IF NOT EXISTS film_statistics AS
SELECT
    f.id as film_id,
    f.name as film_name,
    YEAR(f.releaseDate) as release_year,
    COUNT(DISTINCT l.id) as like_count,
    COUNT(DISTINCT fg.genre_id) as genre_count
FROM films f
LEFT JOIN likes l ON f.id = l.film_id
LEFT JOIN film_genre fg ON f.id = fg.film_id
GROUP BY f.id;

-- Отзывы
CREATE TABLE IF NOT EXISTS reviews (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content TEXT NOT NULL,
    is_positive BOOLEAN NOT NULL,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    film_id BIGINT NOT NULL REFERENCES films(id) ON DELETE CASCADE,
    useful INTEGER DEFAULT 0,
    UNIQUE(user_id, film_id)
);

-- Лайки отзывов
CREATE TABLE IF NOT EXISTS review_likes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id BIGINT NOT NULL REFERENCES reviews(review_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    is_like BOOLEAN NOT NULL,
    UNIQUE(review_id, user_id)
);

-- Объявление ENUM
CREATE TYPE event_type_enum AS ENUM ('LIKE', 'REVIEW', 'FRIEND');
CREATE TYPE operation_enum AS ENUM ('REMOVE', 'ADD', 'UPDATE');

-- Лента новостей
CREATE TABLE IF NOT EXISTS feeds
(
    event_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    event_type event_type_enum NOT NULL,
    operation operation_enum NOT NULL,
    entity_id BIGINT NOT NULL
);